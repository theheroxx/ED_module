    "# ============================================================================\n",
    "# GNN MODEL DEFINITION\n",
    "# ============================================================================\n",
    "\n",
    "class SimpleGCNLayer(nn.Module):\n",
    "    \"\"\"Simple Graph Convolutional Layer.\"\"\"\n",
    "    def __init__(self, in_features, out_features):\n",
    "        super(SimpleGCNLayer, self).__init__()\n",
    "        self.linear = nn.Linear(in_features, out_features)\n",
    "\n",
    "    def forward(self, x, adj):\n",
    "        neighbor_aggr = torch.mm(adj, x)\n",
    "        output = self.linear(neighbor_aggr)\n",
    "        return output\n",
    "\n",
    "\n",
    "class RegionalRiskGNN(nn.Module):\n",
    "    \"\"\"\n",
    "    Regional Risk GNN for predicting location-specific biases.\n",
    "\n",
    "    Architecture (now a genuine residual GCN):\n",
    "        - GCN Layer 1: input_features -> hidden_dim, + projected skip from input\n",
    "        - LayerNorm + ReLU + Dropout\n",
    "        - GCN Layer 2: hidden_dim -> hidden_dim//2, + projected skip from layer-1 output\n",
    "        - LayerNorm + ReLU + Dropout\n",
    "        - GCN Layer 3: hidden_dim//2 -> 1 (bias prediction)\n",
    "\n",
    "    Notes on the two changes from the original version:\n",
    "    - LayerNorm instead of BatchNorm: BatchNorm keeps running mean/var estimated\n",
    "      from training-time (augmented/masked) inputs, then applies them to clean\n",
    "      inputs at eval time. With heavy per-step augmentation those two distributions\n",
    "      diverge, and validation predictions blow up. LayerNorm normalizes each node's\n",
    "      own feature vector independently, so it has no running statistics and no\n",
    "      train/eval mismatch.\n",
    "    - Real residual (skip) connections: since dimensions change between layers,\n",
    "      each skip is a small linear projection of the block's input, added to the\n",
    "      block's output before the nonlinearity. This is what the notebook's name\n",
    "      promised but the original code didn't actually implement, and it also gives\n",
    "      training a more stable gradient path.\n",
    "    \"\"\"\n",
    "    def __init__(self, num_features, hidden_dim=32):\n",
    "        super(RegionalRiskGNN, self).__init__()\n",
    "        self.gc1 = SimpleGCNLayer(num_features, hidden_dim)\n",
    "        self.skip1 = nn.Linear(num_features, hidden_dim)\n",
    "        self.ln1 = nn.LayerNorm(hidden_dim)\n",
    "\n",
    "        self.gc2 = SimpleGCNLayer(hidden_dim, hidden_dim // 2)\n",
    "        self.skip2 = nn.Linear(hidden_dim, hidden_dim // 2)\n",
    "        self.ln2 = nn.LayerNorm(hidden_dim // 2)\n",
    "\n",
    "        self.relu = nn.ReLU()\n",
    "        self.dropout = nn.Dropout(0.5)\n",
    "        self.gc3 = SimpleGCNLayer(hidden_dim // 2, 1)\n",
    "\n",
    "    def forward(self, x, adj):\n",
    "        h = self.gc1(x, adj) + self.skip1(x)\n",
    "        h = self.ln1(h)\n",
    "        h = self.relu(h)\n",
    "        h = self.dropout(h)\n",
    "\n",
    "        h2 = self.gc2(h, adj) + self.skip2(h)\n",
    "        h2 = self.ln2(h2)\n",
    "        h2 = self.relu(h2)\n",
    "        h2 = self.dropout(h2)\n",
    "\n",
    "        out = self.gc3(h2, adj)\n",
    "        return out\n"
